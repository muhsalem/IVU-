import jsPDF from 'jspdf';
import * as XLSX from 'xlsx';
import { CalculationResult } from '../types';

export function exportCalculationToExcel(result: CalculationResult) {
  const data = [
    ['المعيار / البيان', 'القيمة'],
    ['تاريخ بداية العقد', result.startDate],
    ['تاريخ التقييم / النهائي', result.endDate],
    ['نوع العقد', result.contractType],
    ['العملة المعتمدة', result.currency],
    ['المبلغ الاسمي الأصلي', result.nominalAmount],
    ['القيمة المعدلة وفق وحدة IVU', result.ivuValue.toFixed(2)],
    ['القيمة المعدلة وفق الذهب', result.goldValue.toFixed(2)],
    ['القيمة المعدلة وفق التضخم CPI', result.cpiValue.toFixed(2)],
    ['القيمة المعدلة وفق سلة العملات / SDR', result.currencyBasketValue.toFixed(2)],
    ['نسبة التغير في IVU %', `${result.ivuChangePercent.toFixed(2)}%`],
    ['نسبة التضخم واسميته %', `${result.inflationLossPercent.toFixed(2)}%`],
    ['فرق القيمة (مبلغ التعديل العادل بـ IVU)', result.ivuDifferenceAmount.toFixed(2)],
    ['التوجيه الشرعي ومعيار AAOIFI', result.shariahGuidanceAr],
    ['المرجع الشرعي المعتمَد', result.aaoifiReferenceAr]
  ];

  const ws = XLSX.utils.aoa_to_sheet(data);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'تقارير IVU الحسابية');
  XLSX.writeFile(wb, `IVU_Valuation_Report_${result.startDate}_to_${result.endDate}.xlsx`);
}

export function exportCalculationToPdf(result: CalculationResult) {
  const doc = new jsPDF();

  doc.setFontSize(18);
  doc.text('Islamic Value Unit (IVU) - Official Valuation Report', 15, 20);

  doc.setFontSize(12);
  doc.text('Islamic Value Unit Report - Real Value Preservation', 15, 30);
  doc.line(15, 33, 195, 33);

  doc.setFontSize(11);
  doc.text(`Contract Period: ${result.startDate} to ${result.endDate}`, 15, 45);
  doc.text(`Contract Category: ${result.contractType}`, 15, 53);
  doc.text(`Currency: ${result.currency}`, 15, 61);
  doc.text(`Nominal Amount: ${result.nominalAmount.toLocaleString()} ${result.currency}`, 15, 69);

  doc.line(15, 75, 195, 75);
  doc.setFontSize(13);
  doc.text('Comparative Valuation Methods:', 15, 85);

  doc.setFontSize(11);
  doc.text(`- IVU Adjusted Value: ${result.ivuValue.toLocaleString(undefined, {maximumFractionDigits: 2})} ${result.currency} (${result.ivuChangePercent > 0 ? '+' : ''}${result.ivuChangePercent.toFixed(2)}%)`, 20, 95);
  doc.text(`- Gold Standard Adjusted: ${result.goldValue.toLocaleString(undefined, {maximumFractionDigits: 2})} ${result.currency} (${result.goldChangePercent > 0 ? '+' : ''}${result.goldChangePercent.toFixed(2)}%)`, 20, 105);
  doc.text(`- CPI Inflation Adjusted: ${result.cpiValue.toLocaleString(undefined, {maximumFractionDigits: 2})} ${result.currency}`, 20, 115);
  doc.text(`- SDR Currency Basket Adjusted: ${result.currencyBasketValue.toLocaleString(undefined, {maximumFractionDigits: 2})} ${result.currency}`, 20, 125);

  doc.line(15, 135, 195, 135);
  doc.setFontSize(13);
  doc.text('Fair Settlement & Shariah Guidance:', 15, 145);

  doc.setFontSize(10);
  doc.text(`AAOIFI Standard Reference: ${result.aaoifiReferenceAr}`, 15, 155);
  
  // Wrap guidance text
  const splitGuidance = doc.splitTextToSize(`Guidance Summary: ${result.shariahGuidanceAr}`, 175);
  doc.text(splitGuidance, 15, 165);

  doc.setFontSize(9);
  doc.text('Generated by Islamic Value Unit (IVU) Platform - https://ivu-standard.org', 15, 280);

  doc.save(`IVU_Contract_Valuation_${result.startDate}_${result.endDate}.pdf`);
}
